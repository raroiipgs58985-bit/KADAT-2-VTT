function freezeData<T>(value: T): T {
  if (value && typeof value === 'object') {
    Object.freeze(value);
    for (const child of Object.values(value)) freezeData(child);
  }
  return value;
}
export const consequenceCatalog: readonly ConsequenceRow[] = freezeData(
  canonicalRows.map(([zone, range, title, text, sourceRange]) => {
    const bounds = range.replace('+', '').split('-').map(Number),
      id = `${zone}:${range}`;
    const source = {
      kind: 'canonical-source',
      id: `Механика к100.xlsx / Раны и лечение  / ${sourceRange}`,
    };
    return {
      id,
      zone,
      range,
      title,
      text,
      minimum: bounds[0]!,
      maximum: range.endsWith('+') ? null : (bounds[1] ?? bounds[0]!),
      provenance: {
        source,
        record: `Appendix A; ${sourceRange}; ${id}`,
        reason: 'Canonical row reproduced in user-approved C-2 contract',
      },
      operations: consequenceOperations[id]!,
    };
  }),
);

export function validateConsequenceCatalog(catalog: readonly ConsequenceRow[]): void {
  uniqueIds(
    catalog.map((r) => r.id),
    'consequence row IDs',
  );
  for (const zone of ['HEAD', 'ARM', 'TORSO', 'LEG'] as const) {
    const rows = catalog.filter((r) => r.zone === zone).sort((a, b) => a.minimum - b.minimum);
    let next = 1;
    for (const row of rows) {
      integer(row.minimum, 'consequence minimum', 1);
      if (row.minimum !== next) throw new Error('Consequence catalog gap/overlap');
      if (row.maximum !== null) {
        integer(row.maximum, 'consequence maximum', row.minimum);
        next = row.maximum + 1;
      } else next = Infinity;
      if (!row.title || !row.text || !row.provenance.source.id || !Array.isArray(row.operations))
        throw new Error('Incomplete consequence catalog row');
    }
    if (next !== Infinity) throw new Error('Consequence catalog missing terminal range');
  }
  if (catalog.some((r) => !['HEAD', 'ARM', 'TORSO', 'LEG'].includes(r.zone)))
    throw new Error('Unsupported consequence zone');
}
export function lookupConsequence(
  zone: ConsequenceZone,
  severity: number,
  catalog: readonly ConsequenceRow[] = consequenceCatalog,
): ConsequenceRow | null {
  integer(severity, 'consequence severity', 0);
  validateConsequenceCatalog(catalog);
  if (!['HEAD', 'ARM', 'TORSO', 'LEG'].includes(zone))
    throw new Error('Unsupported consequence zone');
  if (severity === 0) return null;
  const row = catalog.find(
    (r) =>
      r.zone === zone && severity >= r.minimum && (r.maximum === null || severity <= r.maximum),
  );
  if (!row) throw new Error('Consequence lookup gap');
  return row;
}
